#!/usr/bin/env python3
"""Turn this host's jobs.toml entries into systemd --user timers.

    projects/jobs-dashboard/install_jobs.py --dry-run   # show what would change
    projects/jobs-dashboard/install_jobs.py             # write, reload, enable

For each job: ~/.config/systemd/user/job-<name>.service (oneshot, appends to
the job's log like cron did, records peak memory after the run) and
job-<name>.timer (OnCalendar, Persistent so a run missed while the host was
off happens at the next boot). Generated units that are no longer in
jobs.toml are stopped and removed; units without the GENERATED header are
never touched. Moving a job from cron: add it here, run this, then delete its
crontab line (both running at once would run it twice).
"""
import argparse
import os
import shlex
import socket
import subprocess
import sys
import tomllib
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parent.parent
UNIT_DIR = Path.home() / ".config/systemd/user"
GENERATED = "# GENERATED by projects/jobs-dashboard/install_jobs.py from jobs.toml - do not edit"
WAIT_NET = ("/bin/sh -c 'for i in $(seq 60); do ip route show default | grep -q . && exit 0; "
            "sleep 2; done; exit 0'")


def load_jobs(path, host):
    jobs = tomllib.loads(Path(path).read_text())["job"]
    names = [j["name"] for j in jobs]
    dup = {n for n in names if names.count(n) > 1}
    if dup:
        sys.exit(f"duplicate job names in jobs.toml: {sorted(dup)}")
    for j in jobs:
        missing = {"name", "host", "desc", "on_calendar", "command", "log"} - j.keys()
        if missing:
            sys.exit(f"job {j.get('name')}: missing {sorted(missing)}")
    return [j for j in jobs if j["host"] == host]


def exec_start(command, repo):
    argv = shlex.split(command)
    if not argv[0].startswith("/"):
        argv[0] = str(repo / argv[0])
    return " ".join(shlex.quote(a) for a in argv)


def render(job, repo=REPO):
    """Return {filename: text} for one job."""
    unit = f"job-{job['name']}"
    log = repo / job["log"]
    svc = [GENERATED, "[Unit]", f"Description={job['desc']}", "",
           "[Service]", "Type=oneshot", f"WorkingDirectory={repo}",
           f"ExecStart={exec_start(job['command'], repo)}",
           f"StandardOutput=append:{log}", f"StandardError=append:{log}",
           "MemoryAccounting=yes",
           f"ExecStopPost=-{repo}/projects/jobs-dashboard/record_run.sh {unit}.service"]
    if job.get("network"):
        svc.insert(svc.index(f"WorkingDirectory={repo}") + 1, f"ExecStartPre={WAIT_NET}")
    if job.get("ok_codes"):
        svc.append("SuccessExitStatus=" + " ".join(str(c) for c in job["ok_codes"]))
    tmr = [GENERATED, "[Unit]", f"Description=Schedule for {unit} (jobs.toml)", "",
           "[Timer]", f"OnCalendar={job['on_calendar']}", "Persistent=true",
           "AccuracySec=1s", "", "[Install]", "WantedBy=timers.target"]
    return {f"{unit}.service": "\n".join(svc) + "\n", f"{unit}.timer": "\n".join(tmr) + "\n"}


def systemctl(*args):
    subprocess.run(["systemctl", "--user", *args], check=True)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--host", default=socket.gethostname())
    a = ap.parse_args()

    jobs = load_jobs(HERE / "jobs.toml", a.host)
    for j in jobs:   # catch a bad calendar before touching anything
        r = subprocess.run(["systemd-analyze", "calendar", j["on_calendar"]],
                           capture_output=True, text=True)
        if r.returncode:
            sys.exit(f"job {j['name']}: bad on_calendar {j['on_calendar']!r}: {r.stderr.strip()}")

    want = {}
    for j in jobs:
        want.update(render(j))
    have = {p.name: p.read_text() for p in UNIT_DIR.glob("job-*")
            if p.is_file() and p.read_text().startswith(GENERATED)}
    changed = [n for n, t in want.items() if have.get(n) != t]
    removed = sorted(set(have) - set(want))

    for n in changed:
        print(("update " if n in have else "add    ") + n)
    for n in removed:
        print("remove " + n)
    if not changed and not removed:
        print("nothing to change")
    if a.dry_run:
        return

    UNIT_DIR.mkdir(parents=True, exist_ok=True)
    for n in [r for r in removed if r.endswith(".timer")]:
        subprocess.run(["systemctl", "--user", "disable", "--now", n])
    for n in removed:
        (UNIT_DIR / n).unlink()
    for n in changed:
        tmp = UNIT_DIR / (n + ".tmp")
        tmp.write_text(want[n])
        os.replace(tmp, UNIT_DIR / n)
    systemctl("daemon-reload")
    timers = [n for n in want if n.endswith(".timer")]
    if timers:
        systemctl("enable", "--now", *timers)
        # a changed timer keeps its old schedule until restarted
        changed_timers = [n for n in changed if n.endswith(".timer") and n in have]
        if changed_timers:
            systemctl("restart", *changed_timers)


if __name__ == "__main__":
    main()
